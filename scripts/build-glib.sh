#!/bin/sh
# Cross-build a static glib (with pcre2, libffi, zlib and proxy-libintl from
# meson wraps) for one target platform.
#
#   scripts/build-glib.sh mingw-x86_64     Windows x86_64, Debian mingw-w64
#   scripts/build-glib.sh android-arm64    Android arm64-v8a, NDK in
#                                          $ANDROID_NDK_HOME, API $ANDROID_API
#                                          (default 21)
#
# Installs into build/deps/TARGET (or $2). The CMake toolchain files in
# cmake/toolchains/ point pkg-config there.
#
# Needs: meson ninja-build pkg-config git curl make, plus
#   mingw-x86_64:  gcc-mingw-w64-x86-64
#   android-arm64: the Android NDK (r28 or newer)

set -eu

GLIB_VERSION=2.74.6
GLIB_SHA256=069cf7e51cd261eb163aaf06c8d1754c6835f31252180aff5814e5afc7757fbc

# Android's libc only has iconv from API 28, glib needs it everywhere but
# Windows (which uses its built-in win_iconv).
LIBICONV_VERSION=1.17
LIBICONV_SHA256=8f74213b56238c85a50a5329f77e06198771e70dd9a739779f4c02f65d971313

TARGET=${1:?usage: $0 mingw-x86_64|android-arm64 [PREFIX]}
ROOT=$(cd "$(dirname "$0")/.." && pwd)
PREFIX=${2:-$ROOT/build/deps/$TARGET}
WORK=$ROOT/build/deps/src

# fetch URL SHA256: download into $WORK (once) and check the checksum.
fetch() {
    file=${1##*/}
    if [ ! -f "$file" ]; then
        curl -fSL -o "$file.part" "$1"
        mv "$file.part" "$file"
    fi
    echo "$2  $file" | sha256sum -c -
}

mkdir -p "$WORK"
cd "$WORK"

case $TARGET in
mingw-x86_64)
    CROSS=$ROOT/scripts/cross/mingw-w64-x86_64.ini
    ;;
android-arm64)
    NDK=${ANDROID_NDK_HOME:-${ANDROID_NDK_ROOT:?set ANDROID_NDK_HOME to the NDK directory}}
    API=${ANDROID_API:-21}
    TC=$NDK/toolchains/llvm/prebuilt/linux-x86_64
    CC=$TC/bin/aarch64-linux-android$API-clang
    [ -x "$CC" ] || { echo "no $CC" >&2; exit 1; }

    fetch "https://ftp.gnu.org/pub/gnu/libiconv/libiconv-$LIBICONV_VERSION.tar.gz" \
        "$LIBICONV_SHA256"
    [ -d "libiconv-$LIBICONV_VERSION" ] || tar xf "libiconv-$LIBICONV_VERSION.tar.gz"
    if [ ! -f "$PREFIX/lib/libiconv.a" ]; then
        rm -rf "libiconv-$TARGET"
        mkdir "libiconv-$TARGET"
        (cd "libiconv-$TARGET" &&
            "../libiconv-$LIBICONV_VERSION/configure" \
                --host=aarch64-linux-android \
                --prefix="$PREFIX" \
                --enable-static --disable-shared --with-pic --disable-nls \
                CC="$CC" AR="$TC/bin/llvm-ar" RANLIB="$TC/bin/llvm-ranlib" \
                CFLAGS="-O2" &&
            make -j"$(nproc)" &&
            make install)
    fi

    CROSS=$WORK/cross-$TARGET.ini
    cat > "$CROSS" <<EOF
# Generated by scripts/build-glib.sh for NDK $NDK, API $API.
[binaries]
c = '$CC'
ar = '$TC/bin/llvm-ar'
strip = '$TC/bin/llvm-strip'
pkg-config = 'pkg-config'

[built-in options]
c_args = ['-I$PREFIX/include']
c_link_args = ['-L$PREFIX/lib']

[host_machine]
system = 'android'
cpu_family = 'aarch64'
cpu = 'aarch64'
endian = 'little'
EOF
    ;;
*)
    echo "unknown target: $TARGET" >&2
    exit 1
    ;;
esac

fetch "https://download.gnome.org/sources/glib/${GLIB_VERSION%.*}/glib-$GLIB_VERSION.tar.xz" \
    "$GLIB_SHA256"
[ -d "glib-$GLIB_VERSION" ] || tar xf "glib-$GLIB_VERSION.tar.xz"

# Keep the host's .pc files out of the cross build.
export PKG_CONFIG_LIBDIR="$PREFIX/lib/pkgconfig"
unset PKG_CONFIG_PATH

builddir=$WORK/glib-$GLIB_VERSION-$TARGET
if [ ! -f "$builddir/build.ninja" ]; then
    meson setup "$builddir" "glib-$GLIB_VERSION" \
        --cross-file "$CROSS" \
        --prefix "$PREFIX" \
        --libdir lib \
        --buildtype release \
        --default-library static \
        --wrap-mode forcefallback \
        -Dtests=false \
        -Dinstalled_tests=false \
        -Dnls=disabled \
        -Dman=false \
        -Dgtk_doc=false \
        -Dsysprof=disabled \
        -Dlibmount=disabled \
        -Dselinux=disabled \
        -Dxattr=false
fi
meson compile -C "$builddir"
meson install -C "$builddir" --quiet

echo "glib $GLIB_VERSION for $TARGET installed in $PREFIX"
